defmodule Novu.Notifications do
  @moduledoc """
  Provide access to the Novu Notifications (activity feed) API
  """

  alias Novu.Http

  @doc """
  Lists notification events (triggered events) for the current environment.

  ## Options

    * `:channels` - list of channel types
    * `:templates` - list of workflow template IDs
    * `:emails` - list of email addresses
    * `:subscriber_ids` - list of subscriber IDs
    * `:severity` - list of severity levels
    * `:page` - page number
    * `:limit` - page size
    * `:transaction_id` - filter by transaction ID
    * `:topic_key` - filter by topic key
    * `:subscription_id` - filter by subscription ID
    * `:context_keys` - list of exact context keys (format `"type:id"`)
    * `:after` - only records after this timestamp (ISO-8601 string or `DateTime`)
    * `:before` - only records before this timestamp (ISO-8601 string or `DateTime`)

  [API Documentation](https://docs.novu.co/api-reference/notifications/list-all-events)
  """
  @spec list_notifications(opts :: keyword()) :: Http.response()
  def list_notifications(opts \\ []) do
    params =
      %{}
      |> add_optional_value(:channels, opts[:channels])
      |> add_optional_value(:templates, opts[:templates])
      |> add_optional_value(:emails, opts[:emails])
      |> add_optional_value(:subscriberIds, opts[:subscriber_ids])
      |> add_optional_value(:severity, opts[:severity])
      |> add_optional_value(:page, opts[:page])
      |> add_optional_value(:limit, opts[:limit])
      |> add_optional_value(:transactionId, opts[:transaction_id])
      |> add_optional_value(:topicKey, opts[:topic_key])
      |> add_optional_value(:subscriptionId, opts[:subscription_id])
      |> add_optional_value(:contextKeys, opts[:context_keys])
      |> add_optional_value(:after, format_datetime(opts[:after]))
      |> add_optional_value(:before, format_datetime(opts[:before]))

    Http.get("/v1/notifications", params)
  end

  @doc """
  Retrieves a notification event by ID.

  The response includes the execution details of the event: jobs, steps,
  execution logs and status, and the messages generated by each workflow step.

  [API Documentation](https://docs.novu.co/api-reference/notifications/retrieve-an-event)
  """
  @spec get_notification(notification_id :: String.t()) :: Http.response()
  def get_notification(notification_id) do
    Http.get("/v1/notifications/#{Http.path_segment(notification_id)}")
  end

  defp format_datetime(%DateTime{} = datetime), do: DateTime.to_iso8601(datetime)
  defp format_datetime(value), do: value

  defp add_optional_value(map, _key, nil), do: map
  defp add_optional_value(map, key, value), do: Map.put(map, key, value)
end
